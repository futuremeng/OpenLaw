package parse

import "testing"

func TestInferEffectLevel(t *testing.T) {
	cases := []struct {
		name  string
		level string
		rule  int
	}{
		{"最高人民法院关于适用《中华人民共和国民事诉讼法》的解释", "司法解释", 1},
		{"最高人民检察院关于人民检察院办理未成年人刑事案件的规定", "司法解释", 1},
		{"中华人民共和国道路交通安全法实施条例", "", 0}, // 名称不带国务院开头（条例类惯名），不猜
		{"国务院中华人民共和国学位条例", "行政法规", 2},
		{"国务院办公厅关于调整…的通知", "", 0}, // 国办文件效力存疑
		{"全国人民代表大会组织法", "法律", 3},
		{"全国人大常委会关于《中华人民共和国刑法》第二百六十六条的解释", "法律", 3},
		{"浙江省广播电视管理条例", "地方性法规", 4},
		{"内蒙古自治区人民政府…", "地方性法规", 4},
		{"新疆维吾尔自治区人民代表大会常务委员会关于修改…的决定", "地方性法规", 4},
		{"吉林省吉林市…", "地方性法规", 4}, // 省前缀优先，不被市规则截获
		{"前郭尔罗斯蒙古族自治县自治条例", "地方性法规", 5},
		{"伊犁哈萨克自治州…的决定", "地方性法规", 5},
		{"海南经济特区林地管理条例", "地方性法规", 5},
		{"吉林市清真食品管理条例", "地方性法规", 6},
		{"呼伦贝尔盟…", "地方性法规", 6},
		{"中华人民共和国宪法", "宪法", 8},
		{"中华人民共和国宪法修正案（2018年）", "宪法", 8},
		{"中华人民共和国矿产资源法", "法律", 7},
		{"中华人民共和国外资保险公司管理条例", "", 0}, // 「X法条例」不是法律（行政法规），不猜
		{"中华人民共和国资产评估法", "法律", 7},
		{"中华人民共和国生物安全法", "法律", 7},
		{"南昌高新技术产业开发区条例_", "", 0},     // 无城市「市」后缀，保守不标
		{"吉林省抚松县森林防火条例_", "地方性法规", 4}, // 名称产物尾巴不影响省前缀
		{"关于加强…的通知", "", 0},
		{"台湾…", "", 0},
	}
	for _, c := range cases {
		level, rule := InferEffectLevel(c.name)
		if level != c.level || rule != c.rule {
			t.Errorf("%q: 期望 (%q,%d)，实际 (%q,%d)", c.name, c.level, c.rule, level, rule)
		}
	}
	if !IsLocalLevel("地方性法规") || IsLocalLevel("法律") {
		t.Error("IsLocalLevel 判定错误")
	}
}
